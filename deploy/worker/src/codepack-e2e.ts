// Full end-to-end lab packs (deterministic). Uses TARGET_URL from the environment.
import type { LabFile, LabKind } from "./codepack-types";

function pythonMainPy(beef: boolean): string {
  const browserFn = beef
    ? lines(
        "",
        "def probe_browser() -> dict:",
        "    from . import http_client",
        "    snap = http_client.get(target_url())",
        "    body = (snap.get('body_sample') or '').lower()",
        "    hints = ['beef', 'hook', 'browser', 'xss']",
        "    return {'target': target_url(), 'beef_hints_in_body': [h for h in hints if h in body]}",
        "",
      )
    : "";
  const choices = beef
    ? '"setup", "recon", "sqli", "xss", "cmdi", "secrets", "browser", "full", "report"'
    : '"setup", "recon", "sqli", "xss", "cmdi", "secrets", "full", "report"';
  const browserBranch = beef
    ? lines(
        '    elif args.cmd == "browser":',
        "        print(json.dumps(probe_browser(), indent=2))",
      )
    : "";
  const browserFull = beef ? "        probe_browser()" : "";
  return lines(
    '"""CLI: python -m src.main <setup|recon|sqli|xss|cmdi|secrets|full|report>"""',
    "from __future__ import annotations",
    "import argparse",
    "import json",
    "",
    "from .config import ensure_evidence, target_url",
    "from . import recon, probes, report",
    browserFn.trim() ? browserFn : "",
    "",
    "def main() -> None:",
    "    ap = argparse.ArgumentParser(description='OHQS end-to-end lab runner')",
    "    ap.add_argument('cmd', choices=[" + choices + "])",
    "    args = ap.parse_args()",
    '    if args.cmd == "setup":',
    "        ensure_evidence()",
    '        print(json.dumps({"target": target_url(), "evidence": "ready"}, indent=2))',
    '    elif args.cmd == "recon":',
    "        print(json.dumps(recon.run(), indent=2))",
    '    elif args.cmd == "sqli":',
    "        print(json.dumps(probes.probe_sqli(), indent=2))",
    '    elif args.cmd == "xss":',
    "        print(json.dumps(probes.probe_xss(), indent=2))",
    '    elif args.cmd == "cmdi":',
    "        print(json.dumps(probes.probe_cmdi(), indent=2))",
    '    elif args.cmd == "secrets":',
    "        print(json.dumps(probes.probe_secrets_on_disk(), indent=2))",
    browserBranch,
    '    elif args.cmd == "full":',
    "        ensure_evidence()",
    "        recon.run()",
    "        probes.probe_sqli()",
    "        probes.probe_xss()",
    "        probes.probe_cmdi()",
    "        probes.probe_secrets_on_disk()",
    browserFull,
    "        print(report.render_findings())",
    "    else:",
    "        print(report.render_findings())",
    "",
    "",
    'if __name__ == "__main__":',
    "    main()",
  );
}

function lines(...rows: string[]): string {
  return rows.join("\n") + "\n";
}

function slug(s: string): string {
  return (
    (s || "lab")
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "")
      .slice(0, 48) || "lab"
  );
}

