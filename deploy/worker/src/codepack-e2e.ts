export function rustE2eFiles(_complexity: number, _kind: LabKind): LabFile[] {
  return [
    {
      path: "Cargo.toml",
      content: lines(
        "[package]",
        'name = "ohqs_lab"',
        'version = "0.1.0"',
        'edition = "2021"',
        "publish = false",
        "",
        "[dependencies]",
        "reqwest = { version = \"0.12\", default-features = false, features = [\"blocking\", \"json\"] }",
        "serde = { version = \"1\", features = [\"derive\"] }",
        "serde_json = \"1\"",
        "url = \"2\"",
      ),
    },
    {
      path: "src/main.rs",
      content: lines(
        "use std::env;",
        "use std::fs;",
        "use std::path::PathBuf;",
        "use std::time::Instant;",
        "",
        "fn target() -> String {",
        '    env::var("TARGET_URL").unwrap_or_else(|_| "https://lab.example.invalid".into())',
        "}",
        "",
        "fn evidence() -> PathBuf {",
        '    PathBuf::from("evidence")',
        "}",
        "",
        "fn get(client: &reqwest::blocking::Client, url: &str) -> Result<(u16, String), reqwest::Error> {",
        "    let resp = client.get(url).send()?;",
        "    let status = resp.status().as_u16();",
        "    let body = resp.text().unwrap_or_default();",
        "    Ok((status, body))",
        "}",
        "",
        "fn inject_q(base: &str, val: &str) -> String {",
        "    if let Ok(mut u) = url::Url::parse(base) {",
        "        let mut pairs: Vec<(String, String)> = u",
        "            .query_pairs()",
        "            .into_owned()",
        "            .collect();",
        "        if pairs.is_empty() {",
        '            pairs.push(("q".into(), val.into()));',
        "        } else {",
        "            pairs[0].1 = val.into();",
        "        }",
        "        u.query_pairs_mut().clear();",
        "        for (k, v) in pairs {",
        "            u.query_pairs_mut().append_pair(&k, &v);",
        "        }",
        "        return u.to_string();",
        "    }",
        "    base.to_string()",
        "}",
        "",
        "fn main() {",
        "    let cmd = env::args().nth(1).unwrap_or_else(|| \"full\".into());",
        "    fs::create_dir_all(evidence()).expect(\"evidence\");",
        '    if cmd == "setup" {',
        "        println!(\"target: {}\", target());",
        "        return;",
        "    }",
        "    let client = reqwest::blocking::Client::builder()",
        '        .user_agent("ohqs-lab/1.0")',
        "        .build()",
        "        .expect(\"client\");",
        "    let t = target();",
        "    let (status, body) = get(&client, &t).expect(\"recon get\");",
        "    let recon = serde_json::json!({\"target\": t, \"status\": status, \"body_len\": body.len()});",
        '    fs::write(evidence().join("recon.json"), serde_json::to_string_pretty(&recon).unwrap()).unwrap();',
        "    let sqli_url = inject_q(&t, \"' OR '1'='1\");",
        "    let (_, sq_body) = get(&client, &sqli_url).unwrap_or((0, String::new()));",
        "    let sqli_leak = sq_body.to_lowercase().contains(\"sql\");",
        "    let xss_url = inject_q(&t, \"<svg/onload=ohqs>\");",
        "    let (_, x_body) = get(&client, &xss_url).unwrap_or((0, String::new()));",
        "    let xss = x_body.contains(\"<svg/onload=ohqs>\");",
        "    let cmd_url = inject_q(&t, \";sleep 2\");",
        "    let start = Instant::now();",
        "    let _ = get(&client, &cmd_url);",
        "    let timed = start.elapsed().as_millis() >= 1800;",
        "    let probes = serde_json::json!({\"sqli_error_leak\": sqli_leak, \"xss_reflected\": xss, \"cmdi_timed\": timed});",
        '    fs::write(evidence().join("probes.json"), serde_json::to_string_pretty(&probes).unwrap()).unwrap();',
        '    println!("probes complete — see evidence/");',
        "}",
      ),
    },
  ];
}

export function jsE2eFiles(_complexity: number, _kind: LabKind): LabFile[] {
  return [
    {
      path: "package.json",
      content:
        JSON.stringify(
          {
            name: "ohqs-lab",
            version: "0.1.0",
            private: true,
            type: "module",
            description: "OpenHat end-to-end web assessment runner",
            scripts: {
              setup: "node src/index.js setup",
              full: "node src/index.js full",
              start: "node src/index.js full",
            },
          },
          null,
          2,
        ) + "\n",
    },
    {
      path: "src/index.js",
      content: lines(
        "import fs from 'node:fs';",
        "import path from 'node:path';",
        "import { fileURLToPath } from 'node:url';",
        "",
        "const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');",
        "const evidence = path.join(root, 'evidence');",
        "",
        "function target() {",
        "  return (process.env.TARGET_URL || 'https://lab.example.invalid').trim();",
        "}",
        "",
        "async function get(url) {",
        "  const res = await fetch(url, {",
        "    redirect: 'follow',",
        "    headers: { 'User-Agent': 'ohqs-lab/1.0' },",
        "  });",
        "  const text = await res.text();",
        "  const sample = text.slice(0, 4000);",
        "  fs.mkdirSync(evidence, { recursive: true });",
        "  fs.writeFileSync(",
        "    path.join(evidence, 'last_response.json'),",
        "    JSON.stringify({ url: res.url, status: res.status, body_sample: sample }, null, 2),",
        "  );",
        "  return { status: res.status, sample };",
        "}",
        "",
        "function injectQuery(base, param, val) {",
        "  const u = new URL(base);",
        "  u.searchParams.set(param, val);",
        "  return u.toString();",
        "}",
        "",
        "async function runFull() {",
        "  const t = target();",
        "  const recon = await get(t);",
        "  fs.writeFileSync(path.join(evidence, 'recon.json'), JSON.stringify({ target: t, ...recon }, null, 2));",
        "  const sqli = await get(injectQuery(t, 'q', \"' OR '1'='1\"));",
        "  const sqliLeak = /sql|mysql|sqlite|postgresql/i.test(sqli.sample);",
        "  const xssPayload = '<svg/onload=ohqs>';",
        "  const xss = await get(injectQuery(t, 'q', xssPayload));",
        "  const reflected = xss.sample.includes(xssPayload);",
        "  const t0 = Date.now();",
        "  await get(injectQuery(t, 'q', ';sleep 2'));",
        "  const timed = Date.now() - t0 >= 1800;",
        "  const probes = { sqli_error_leak: sqliLeak, xss_reflected: reflected, cmdi_timed: timed };",
        "  fs.writeFileSync(path.join(evidence, 'probes.json'), JSON.stringify(probes, null, 2));",
        "  console.log(JSON.stringify(probes, null, 2));",
        "}",
        "",
        "const cmd = process.argv[2] || 'full';",
        "if (cmd === 'setup') {",
        "  fs.mkdirSync(evidence, { recursive: true });",
        "  console.log(JSON.stringify({ target: target() }, null, 2));",
        "} else {",
        "  runFull().catch((e) => {",
        "    console.error(e);",
        "    process.exit(1);",
        "  });",
        "}",
      ),
    },
  ];
}
